"""Markdown rendering of an evaluation run.

The report is written so a reader who skims it cannot come away with a rosier
impression than the numbers support. Cross-dataset figures lead; in-dataset
figures are shown but labelled as the ones that flatter. Anything unmeasurable
says so instead of being omitted, because a missing row reads as "fine".
"""

from __future__ import annotations

from pathlib import Path


def _fmt(value: float | None, digits: int = 4) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def _threshold_rows(entries: list[dict]) -> list[str]:
    rows = []
    for entry in entries:
        target = f"{entry['target_fpr']:.1%}"
        if entry["measurable"]:
            rows.append(
                f"| TPR @ FPR={target} | {entry['tpr']:.4f} | {entry['note']} |"
            )
        else:
            rows.append(f"| TPR @ FPR={target} | not measurable | {entry['note']} |")
    return rows


def write_report(path: Path, payload: dict) -> None:
    p = payload["provenance"]
    datasets = payload["datasets"]
    coverage = payload["coverage"]
    cross = payload["cross_dataset_metrics"]
    in_dataset = payload["in_dataset_metrics"]

    calib_key = p["calibration_dataset"]
    report_key = p["reporting_dataset"]

    lines: list[str] = []
    add = lines.append

    add(f"# VeriFrame evaluation — {p['generated_at'][:10]}")
    add("")
    add(
        "Generated by `services/inference/eval/run.py`. Every number in the product "
        "must trace to a row in this file; nothing here is hand-entered."
    )
    add("")

    # --- Headline caveats first, so they cannot be skipped ---
    add("## Read this before quoting any number")
    add("")
    add(
        f"- **Sample size.** {p['samples_per_dataset']} images were drawn per corpus. "
        "That is enough for a stable AUC and for fitting a single calibration "
        "parameter. It is *not* enough to measure true-positive rate at very low "
        "false-positive rates; those rows say so explicitly rather than showing a "
        "number built from a handful of events."
    )
    add(
        "- **Possible contamination.** The classifier's training data is not "
        "published in full, so we cannot rule out overlap between it and these "
        "evaluation corpora. If overlap exists, these figures are optimistic."
    )
    add(
        "- **These are not accuracy claims for arbitrary media.** They describe "
        "performance on two specific corpora. Deepfake detectors degrade sharply on "
        "generators they have not seen, and the generators in circulation change "
        "faster than any fixed evaluation set."
    )
    add("")

    add("## Protocol")
    add("")
    add(
        f"Calibration was fitted on **{calib_key}** and every headline figure is "
        f"reported on **{report_key}**, which shares no images with it. In-dataset "
        "figures appear further down purely for contrast — they are the numbers that "
        "flatter, and the ones most published results quote."
    )
    add("")
    add("| Corpus | Role | Licence | Commercial use | Scored | No face detected |")
    add("|---|---|---|---|---|---|")
    for key, role in ((calib_key, "calibration"), (report_key, "reporting")):
        meta = datasets[key]
        cov = coverage[key]
        add(
            f"| `{meta['hf_id']}` | {role} | {meta['licence']} | "
            f"{'yes' if meta['commercial_use'] else '**no**'} | "
            f"{cov['scored']} | {cov['no_face_detected']} |"
        )
    add("")

    # --- Cross-dataset: the headline ---
    add("## Cross-dataset results (headline)")
    add("")
    if not cross:
        add("_No stream produced enough scored samples to report._")
    for stream, entry in cross.items():
        raw = entry["raw"]
        calibrated = entry["calibrated"]
        add(f"### Stream: {stream}")
        add("")
        add(f"n = {raw['n']} ({raw['n_positive']} manipulated, {raw['n_negative']} authentic)")
        add("")
        add("| Metric | Value | Note |")
        add("|---|---|---|")
        lo, hi = raw["auc_ci95"]
        add(f"| AUC | {raw['auc']:.4f} | 95% CI {lo:.4f}–{hi:.4f} (bootstrap) |")
        add(f"| EER | {raw['eer']:.4f} | at threshold {raw['eer_threshold']:.4f} |")
        lines.extend(_threshold_rows(raw["thresholds"]))
        add(
            f"| ECE before calibration | {raw['ece']:.4f} | gap between claimed and observed |"
        )
        add(f"| ECE after calibration | {calibrated['ece']:.4f} | temperature scaling applied |")
        add(
            f"| Mean score, manipulated | {raw['mean_score_positive']:.4f} | |"
        )
        add(f"| Mean score, authentic | {raw['mean_score_negative']:.4f} | |")
        add("")

        if calibrated["ece"] < raw["ece"]:
            add(
                f"Calibration reduced ECE from {raw['ece']:.4f} to {calibrated['ece']:.4f}. "
                "AUC is unchanged by construction — temperature scaling alters confidence, "
                "not ranking."
            )
        else:
            add(
                f"Calibration did **not** improve ECE on this corpus "
                f"({raw['ece']:.4f} → {calibrated['ece']:.4f}), which is what you would "
                "expect when the calibration corpus and the reporting corpus differ in "
                "difficulty. This is the honest outcome of a cross-dataset protocol."
            )
        add("")

    # --- Fusion weights ---
    add("## Fusion weights")
    add("")
    add(
        "Derived from measured validation AUC, never hand-picked. Weight is "
        "proportional to how far a stream sits above chance, normalised across "
        "streams. A stream at or below chance receives zero."
    )
    add("")
    add("| Stream | Validation AUC | Weight | Rationale |")
    add("|---|---|---|---|")
    for entry in payload["fusion_weights"]:
        add(
            f"| {entry['stream']} | {entry['auc']:.4f} | {entry['weight']:.4f} | "
            f"{entry['rationale']} |"
        )
    add("")

    prov = payload.get("provenance_stream")
    if prov and not prov.get("measurable", True):
        add("### Stream D (provenance) — not measurable on these corpora")
        add("")
        add(prov["note"])
        add("")
        add(
            f"It fired on {prov['fired_on_calibration_split']} calibration and "
            f"{prov['fired_on_reporting_split']} reporting images."
        )
        add("")

    add("## Calibration parameters")
    add("")
    add("| Stream | Temperature |")
    add("|---|---|")
    for stream, temperature in payload["temperature"].items():
        add(f"| {stream} | {temperature:.4f} |")
    add("")
    add(
        "Temperature > 1 softens an overconfident model; < 1 sharpens an "
        "underconfident one. Fitted by minimising negative log-likelihood on the "
        "calibration split only."
    )
    add("")

    # --- Robustness ---
    robustness = payload.get("robustness_auc_by_jpeg_quality") or {}
    if robustness:
        add("## Robustness to recompression")
        add("")
        add(
            "AUC on the reporting corpus after re-encoding at each JPEG quality. Most "
            "media arrives recompressed, so this is closer to deployment conditions "
            "than the headline figure."
        )
        add("")
        streams = sorted({s for entry in robustness.values() for s in entry})
        add("| JPEG quality | " + " | ".join(streams) + " |")
        add("|---" * (len(streams) + 1) + "|")
        for quality in sorted(robustness, key=lambda q: -int(q)):
            row = robustness[quality]
            add(
                f"| q{quality} | "
                + " | ".join(_fmt(row.get(s)) for s in streams)
                + " |"
            )
        add("")

    # --- In-dataset, deliberately last ---
    add("## In-dataset results (for contrast only)")
    add("")
    add(
        f"Measured on **{calib_key}**, the same corpus calibration was fitted on. "
        "These are not a performance claim. They are included so the gap against the "
        "cross-dataset figures above is visible, since that gap is the whole reason "
        "the cross-dataset protocol is mandatory."
    )
    add("")
    add("| Stream | AUC | EER |")
    add("|---|---|---|")
    for stream, entry in in_dataset.items():
        add(f"| {stream} | {entry['auc']:.4f} | {entry['eer']:.4f} |")
    add("")

    add("---")
    add("")
    add(
        "Detection is advisory. These figures describe measured behaviour on fixed "
        "corpora and are not proof about any individual image."
    )
    add("")

    path.write_text("\n".join(lines), encoding="utf-8")
