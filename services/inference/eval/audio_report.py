"""Markdown rendering of an audio evaluation run. Mirrors report.py's structure
and honesty rules (cross-dataset leads, in-dataset is labelled as what flatters,
unmeasurable says so) with audio-appropriate framing in place of image-specific
wording (clips rather than images, no face-detection column, a noise-based
robustness sweep rather than a JPEG-quality one).
"""

from __future__ import annotations

from pathlib import Path


def _fmt(value: float | None, digits: int = 4) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def _threshold_rows(entries: list[dict]) -> list[str]:
    rows = []
    for entry in entries:
        target = f"{entry['target_fpr']:.1%}"
        if entry["measurable"]:
            rows.append(f"| TPR @ FPR={target} | {entry['tpr']:.4f} | {entry['note']} |")
        else:
            rows.append(f"| TPR @ FPR={target} | not measurable | {entry['note']} |")
    return rows


_STREAM_LABELS = {
    "audio": "AASIST",
    "audio_frequency": "harmonics-to-noise ratio (this project's own, unsupervised)",
}


def write_audio_report(path: Path, payload: dict) -> None:
    p = payload["provenance"]
    datasets = payload["datasets"]
    coverage = payload["coverage"]
    cross = payload["cross_dataset_metrics"]
    in_dataset = payload["in_dataset_metrics"]
    validation = payload.get("weight_validation_metrics") or {}

    calib_key = p["calibration_dataset"]
    report_key = p["reporting_dataset"]

    lines: list[str] = []
    add = lines.append

    add(f"# VeriFrame audio evaluation — {p['generated_at'][:10]}")
    add("")
    add(
        "Generated by `services/inference/eval/audio_run.py`. Every number in the "
        "product must trace to a row in this file; nothing here is hand-entered."
    )
    add("")

    add("## Read this before quoting any number")
    add("")
    add(
        f"- **Sample size.** {p['samples_per_dataset']} calibration clips, "
        f"{p.get('validation_samples', '?')} weight-validation clips, and "
        f"{p.get('final_reporting_samples', '?')} final held-out reporting clips. "
        "That is enough for a stable AUC and for fitting a single calibration "
        "parameter. It is *not* enough to measure true-positive rate at very low "
        "false-positive rates; those rows say so explicitly rather than showing a "
        "number built from a handful of events."
    )
    add(
        "- **The calibration corpus is what AASIST was trained on.** Unlike the "
        "image classifier, AASIST's training data provenance is fully documented "
        "(ASVspoof2019 LA), so 'in-dataset' here is a known quantity, not a "
        "contamination risk of unknown extent."
    )
    add(
        "- **Fusion weights come from a genuine cross-dataset split, not the "
        "calibration corpus.** Earlier runs derived weights from calibration-split "
        "AUC — in-distribution performance — which does not predict cross-dataset "
        "generalisation and previously produced a fusion weight that made "
        "cross-dataset AUC *worse* (see DECISIONS.md). The reporting corpus is now "
        "split once, stratified by label, into a weight-validation half and a "
        "final reporting half. Weights are derived from the validation half; every "
        "headline number below comes from the final half, which played no part in "
        "choosing them."
    )
    add(
        "- **These are not accuracy claims for arbitrary audio.** They describe "
        "performance on two specific corpora of studio-adjacent TTS/voice-conversion "
        "attacks. Real-world audio — phone calls, compressed voice notes, background "
        "noise — is exactly the out-of-distribution condition `audio_envelope.py` "
        "flags with a confidence penalty, and generators in circulation change "
        "faster than any fixed evaluation set."
    )
    add("")

    add("## Protocol")
    add("")
    add(
        f"Calibration was fitted on **{calib_key}** and every headline figure is "
        f"reported on **{report_key}**, which shares no utterances with it and uses "
        "different attack algorithms and codec/transmission conditions. The "
        f"{report_key} pool is itself split once, stratified by label, into a "
        "weight-validation half (used only to derive the fusion weight below) and "
        "a final held-out half (used only for the headline numbers). In-dataset "
        "figures appear further down purely for contrast — they are the numbers "
        "that flatter, and the ones most published results quote."
    )
    add("")
    add("| Corpus | Role | Licence | Commercial use | Scored |")
    add("|---|---|---|---|---|")
    calib_meta, calib_cov = datasets[calib_key], coverage[calib_key]
    add(
        f"| `{calib_meta['hf_id']}` | calibration | {calib_meta['licence']} | "
        f"{'yes' if calib_meta['commercial_use'] else '**no**'} | {calib_cov['scored']} |"
    )
    report_meta, report_cov = datasets[report_key], coverage[report_key]
    for role, count_key in (
        ("weight validation", "validation_scored"),
        ("final reporting", "final_reporting_scored"),
    ):
        add(
            f"| `{report_meta['hf_id']}` | {role} | {report_meta['licence']} | "
            f"{'yes' if report_meta['commercial_use'] else '**no**'} | "
            f"{report_cov.get(count_key, '?')} |"
        )
    add("")

    add("## Cross-dataset results (headline)")
    add("")
    if not cross:
        add("_Not enough scored samples to report._")
    for stream, entry in cross.items():
        raw = entry["raw"]
        calibrated = entry["calibrated"]
        label = _STREAM_LABELS.get(stream, stream)
        add(f"### Stream: {stream} ({label})")
        add("")
        add(f"n = {raw['n']} ({raw['n_positive']} spoof, {raw['n_negative']} bonafide)")
        add("")
        add("| Metric | Value | Note |")
        add("|---|---|---|")
        lo, hi = raw["auc_ci95"]
        add(f"| AUC | {raw['auc']:.4f} | 95% CI {lo:.4f}–{hi:.4f} (bootstrap) |")
        add(f"| EER | {raw['eer']:.4f} | at threshold {raw['eer_threshold']:.4f} |")
        lines.extend(_threshold_rows(raw["thresholds"]))
        add(
            f"| ECE before calibration | {raw['ece']:.4f} | gap between claimed and observed |"
        )
        add(f"| ECE after calibration | {calibrated['ece']:.4f} | temperature scaling applied |")
        add(f"| Mean score, spoof | {raw['mean_score_positive']:.4f} | |")
        add(f"| Mean score, bonafide | {raw['mean_score_negative']:.4f} | |")
        add("")

        if calibrated["ece"] < raw["ece"]:
            add(
                f"Calibration reduced ECE from {raw['ece']:.4f} to {calibrated['ece']:.4f}. "
                "AUC is unchanged by construction — temperature scaling alters confidence, "
                "not ranking."
            )
        else:
            add(
                f"Calibration did **not** improve ECE on this corpus "
                f"({raw['ece']:.4f} → {calibrated['ece']:.4f}), which is what you would "
                "expect when the calibration corpus and the reporting corpus differ in "
                "difficulty. This is the honest outcome of a cross-dataset protocol."
            )
        add("")

    fused = payload.get("fused_cross_dataset_metrics")
    audio_only = cross.get("audio", {}).get("raw")
    if fused and audio_only:
        add("## Does the second stream actually help?")
        add("")
        add(
            "The whole reason `audio_frequency` (harmonics-to-noise ratio, this "
            "project's own unsupervised measurement -- see DECISIONS.md) was added: "
            "does fusing it with AASIST improve on AASIST alone, on the held-out "
            "corpus? Reported honestly either way."
        )
        add("")
        add("| | AASIST alone | Fused (AASIST + audio_frequency) | Δ |")
        add("|---|---|---|---|")
        delta_auc = fused["auc"] - audio_only["auc"]
        delta_eer = fused["eer"] - audio_only["eer"]
        add(
            f"| AUC | {audio_only['auc']:.4f} | {fused['auc']:.4f} | "
            f"{'+' if delta_auc >= 0 else ''}{delta_auc:.4f} |"
        )
        add(
            f"| EER | {audio_only['eer']:.4f} | {fused['eer']:.4f} | "
            f"{'+' if delta_eer >= 0 else ''}{delta_eer:.4f} (lower is better) |"
        )
        add("")
        if delta_auc > 0:
            add(
                f"Fusion **improved** cross-dataset AUC by {delta_auc:.4f}. The "
                "fusion weight below is derived entirely from measured AUC on the "
                "weight-validation half of this same cross-dataset corpus -- "
                "nothing here was hand-tuned to produce this result, and the number "
                "above comes from the other, untouched half."
            )
        elif delta_auc < 0:
            add(
                f"Fusion **did not improve** cross-dataset AUC (Δ {delta_auc:.4f}). "
                "AASIST alone generalises better on this corpus than the fused "
                "score does. This is still a legitimate, reportable outcome of "
                "the experiment, not a failure to hide -- see DECISIONS.md."
            )
        else:
            add("Fusion left cross-dataset AUC unchanged.")
        add("")
    elif fused is None and audio_only:
        add(
            "## Does the second stream actually help?\n\n"
            "_Not enough audio_frequency-scored samples on the reporting split "
            "to answer this -- likely too many clips had no measurable "
            "periodicity (silence, heavy noise, non-speech audio)._\n"
        )

    if validation:
        add("## Weight-selection validation")
        add("")
        add(
            "The AUC each stream measures on the weight-validation half above -- a "
            f"held-out slice of **{report_key}**, disjoint from the final reporting "
            "half -- and the only number the fusion weight below is derived from."
        )
        add("")
        add("| Stream | Validation AUC (this decides the weight) |")
        add("|---|---|")
        for stream, entry in validation.items():
            add(f"| {stream} | {entry['auc']:.4f} |")
        add("")

    add("## Fusion weight")
    add("")
    add(
        "Derived from measured AUC on the weight-validation half of the reporting "
        "corpus -- a genuine cross-dataset measurement, not the calibration "
        "corpus's in-distribution AUC (see 'Read this before quoting any number' "
        "above for why that distinction matters). There is currently one audio "
        "stream with signal, so this is normally close to 1.0 by construction "
        "unless the measured AUC is at or below chance."
    )
    add("")
    add("| Stream | Validation AUC | Weight | Rationale |")
    add("|---|---|---|---|")
    for entry in payload["fusion_weights"]:
        add(
            f"| {entry['stream']} | {entry['auc']:.4f} | {entry['weight']:.4f} | "
            f"{entry['rationale']} |"
        )
    add("")

    add("## Calibration parameters")
    add("")
    add("| Stream | Temperature |")
    add("|---|---|")
    for stream, temperature in payload["temperature"].items():
        add(f"| {stream} | {temperature:.4f} |")
    add("")
    add(
        "Temperature > 1 softens an overconfident model; < 1 sharpens an "
        "underconfident one. Fitted by minimising negative log-likelihood on the "
        "calibration split only."
    )
    add("")

    robustness = payload.get("robustness_auc_by_snr_db") or {}
    if robustness:
        add("## Robustness to background noise")
        add("")
        add(
            "AUC on the reporting corpus after adding white Gaussian noise at each "
            "signal-to-noise ratio. Real-world audio — phone calls, voice notes, "
            "ambient recordings — routinely arrives with far more noise than a studio "
            "recording, so this is closer to deployment conditions than the headline "
            "figure."
        )
        add("")
        streams = sorted({s for entry in robustness.values() for s in entry})
        add("| SNR (dB) | " + " | ".join(streams) + " |")
        add("|---" * (len(streams) + 1) + "|")
        for snr in sorted(robustness, key=lambda x: -float(x)):
            row = robustness[snr]
            add(f"| {snr} | " + " | ".join(_fmt(row.get(s)) for s in streams) + " |")
        add("")

    add("## In-dataset results (for contrast only)")
    add("")
    add(
        f"Measured on **{calib_key}**, the same corpus calibration was fitted on and "
        "AASIST itself was trained on. These are not a performance claim. They are "
        "included so the gap against the cross-dataset figures above is visible, "
        "since that gap is the whole reason the cross-dataset protocol is mandatory."
    )
    add("")
    add("| Stream | AUC | EER |")
    add("|---|---|---|")
    for stream, entry in in_dataset.items():
        add(f"| {stream} | {entry['auc']:.4f} | {entry['eer']:.4f} |")
    add("")

    add("---")
    add("")
    add(
        "Detection is advisory. These figures describe measured behaviour on fixed "
        "corpora and are not proof about any individual clip."
    )
    add("")

    path.write_text("\n".join(lines), encoding="utf-8")
