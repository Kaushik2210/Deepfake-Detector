"""Temperature scaling and fusion-weight derivation.

Raw softmax outputs are overconfident. Temperature scaling divides the logit by a
single learned scalar, which changes how confident the score is without changing
how the samples are ranked — so AUC is unaffected and only calibration improves.
Fitting a single parameter is deliberate: with a few thousand samples anything
richer would overfit the validation split.

Fusion weights are derived from each stream's measured validation AUC, never
hand-picked. A stream that turns out to carry no signal gets a weight near zero
as a consequence of measurement, not of anyone's opinion about it.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np


def _logit(p: np.ndarray, eps: float = 1e-6) -> np.ndarray:
    p = np.clip(p, eps, 1.0 - eps)
    return np.log(p / (1.0 - p))


def _sigmoid(z: np.ndarray) -> np.ndarray:
    return 1.0 / (1.0 + np.exp(-z))


def apply_temperature(scores: np.ndarray, temperature: float) -> np.ndarray:
    """Rescale probabilities by dividing their logits by `temperature`.

    T > 1 softens (less confident), T < 1 sharpens. Ranking is preserved.
    """
    if temperature <= 0:
        raise ValueError(f"temperature must be positive, got {temperature}")
    return _sigmoid(_logit(np.asarray(scores, dtype=float)) / temperature)


def fit_temperature(
    labels: np.ndarray,
    scores: np.ndarray,
    grid: np.ndarray | None = None,
) -> tuple[float, float]:
    """Find the temperature minimising negative log-likelihood.

    A grid search over a single bounded parameter is used rather than gradient
    descent: it cannot diverge, is trivially reproducible, and the resolution is
    far finer than the sampling error on a few thousand points.

    Returns (temperature, NLL at that temperature).
    """
    labels = np.asarray(labels, dtype=float)
    scores = np.asarray(scores, dtype=float)

    if grid is None:
        grid = np.concatenate([np.arange(0.05, 1.0, 0.01), np.arange(1.0, 10.01, 0.05)])

    best_t, best_nll = 1.0, float("inf")
    for temperature in grid:
        calibrated = np.clip(apply_temperature(scores, float(temperature)), 1e-7, 1 - 1e-7)
        nll = float(
            -np.mean(labels * np.log(calibrated) + (1 - labels) * np.log(1 - calibrated))
        )
        if nll < best_nll:
            best_t, best_nll = float(temperature), nll

    return best_t, best_nll


@dataclass
class StreamWeight:
    stream: str
    auc: float
    weight: float
    rationale: str


def derive_fusion_weights(stream_aucs: dict[str, float]) -> list[StreamWeight]:
    """Turn measured validation AUCs into fusion weights.

    A stream's usefulness is how far its AUC sits above chance, so weights are
    proportional to (AUC - 0.5) clamped at zero and then normalised. A stream at
    or below chance contributes nothing — which is the correct outcome, and one
    the measurement is allowed to reach on its own.

    An AUC below 0.5 is not inverted to extract signal. Doing so would be fitting
    to the validation split rather than measuring, and would produce a detector
    whose reasoning we cannot explain.
    """
    informativeness = {
        name: max(0.0, auc - 0.5) for name, auc in stream_aucs.items()
    }
    total = sum(informativeness.values())

    weights: list[StreamWeight] = []
    for name, auc in sorted(stream_aucs.items(), key=lambda kv: -kv[1]):
        lift = informativeness[name]

        if total <= 0:
            weight = 0.0
            rationale = "no stream measured above chance; fusion cannot be weighted"
        elif lift == 0.0:
            weight = 0.0
            rationale = (
                f"AUC {auc:.3f} is at or below chance on the validation split, so this "
                "stream contributes nothing to the fused score"
            )
        else:
            weight = lift / total
            rationale = f"AUC {auc:.3f}, i.e. {lift:.3f} above chance, normalised across streams"

        weights.append(
            StreamWeight(
                stream=name,
                auc=round(auc, 4),
                weight=round(weight, 4),
                rationale=rationale,
            )
        )

    return weights


def write_calibration(
    path: Path,
    temperatures: dict[str, float],
    weights: list[StreamWeight],
    provenance: dict,
) -> None:
    """Persist fitted parameters for the inference service to load."""
    payload = {
        "_comment": (
            "Generated by services/inference/eval/run.py. Do not hand-edit: every "
            "value here traces to a row in the eval report named under 'provenance'."
        ),
        "provenance": provenance,
        "temperature": temperatures,
        "stream_weights": {w.stream: w.weight for w in weights},
        "stream_weight_rationale": {w.stream: w.rationale for w in weights},
        "stream_validation_auc": {w.stream: w.auc for w in weights},
    }
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
